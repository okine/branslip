android {
    compileSdk = 37
    namespace = "com.okine.shizhijian"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "com.okine.shizhijian"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            // 注意：debug 构建的 .so 一定会带调试符号（AGP 只在 release 才 strip），
            // 所以 debug APK 就是 ~150 MB；要小包请用 release（见下面 signingConfig）。
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            optimization {
               enable = true
            }
            // 个人自用：先用 debug keystore 给 release 签名，省掉 keystore.properties
            // 配置，`tauri android build --apk` 就能直接出可安装的小包（~15 MB）。
            // 要发布/上架时，换成自己的 signingConfigs.release。
            signingConfig = signingConfigs.getByName("debug")
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
